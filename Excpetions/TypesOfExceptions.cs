    /*Исключения, связанные с системой:

    System.SystemException: Базовый класс для исключений, генерируемых системой. Редко используется напрямую.

        System.OutOfMemoryException: Недостаточно памяти для выполнения операции.

        System.StackOverflowException: Переполнение стека вызовов, обычно вызвано бесконечной рекурсией.

        System.ArithmeticException: Базовый класс для арифметических исключений.

        System.DivideByZeroException: Деление на ноль.

        System.OverflowException: Переполнение при арифметической операции.

        System.InvalidOperationException: Операция недопустима в текущем состоянии объекта.

        Исключения, связанные с данными и вводом/выводом:

    System.ArgumentException: Недопустимое значение аргумента метода.

        System.ArgumentNullException: Аргумент метода имеет значение null, когда это недопустимо.

        System.ArgumentOutOfRangeException: Значение аргумента метода находится вне допустимого диапазона.

        System.FormatException: Неверный формат данных (например, при парсинге строки).

    System.IndexOutOfRangeException: Индекс выходит за пределы границ массива или коллекции.

        System.InvalidCastException: Недопустимое приведение типов.

        System.NullReferenceException: Попытка разыменовать нулевую ссылку.

        System.IO.IOException: Ошибка ввода/вывода (например, при работе с файлами).

    Исключения, связанные с приложениями:

    System.ApplicationException: Базовый класс для исключений, специфичных для приложения. Используйте этот класс или создавайте свои собственные исключения, наследуемые от него, для обработки ошибок, связанных с логикой вашего приложения.*/
}